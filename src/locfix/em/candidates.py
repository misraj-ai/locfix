"""Stage 3 candidates z_k (spec 06 §2).

Two steps:

1. `locfix em.candidates` (GPU): for every Stage 3 task, the **other fold's** localizer answers the
   task's localizer prompt (the teacher's exploration, `em.tasks.localizer_prompt`) `em.K` times at
   `em.sample_temperature`. The prompt is rendered with the training renderer (the tokens the
   localizer was trained on) and generated by vLLM on the real `-w4a16-ct` base with the fold
   localizer as a LoRA. Raw texts are kept (`samples.jsonl`); nothing is filtered here.

2. `assemble()` (CPU, called by `score.prepare`): parse each sample into z, clean it against the
   task's files (unknown paths dropped, line ranges clamped, then the spec 04 §3 rules: at most
   `em.max_locations`, `em.ctx_budget_tokens`), deduplicate, and build the candidate list:

       cand 0      z_T (teacher label: the round-0 localizer target), always
       cand 1..    unique samples, in sampling order
       then        perturbations of z_T (edit_only, view_only, gold_minus_one) while fewer than
                   K + 1 candidates

   A sample equal to z_T counts as a duplicate of cand 0 (`n_samples_equal_teacher`, a diagnostic:
   how often the fold localizer reproduces the teacher label).
"""
from __future__ import annotations

import argparse
import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from ..data.locations import Location, normalize_path
from ..data.zloc import key, parse_z, prune
from ..render.chat import THOUGHT_END, TURN_END

TOOL_CALL_START = "<|tool_call>"


# --------------------------------------------------------------------------- parsing
def parse_sample(text: str) -> tuple[list[Location] | None, str]:
    """(z, "ok") or (None, reason). `text` is the raw generation (special tokens kept)."""
    if TOOL_CALL_START in text:
        return None, "tool_call"                       # explores further instead of answering
    body = text.rsplit(THOUGHT_END, 1)[-1] if THOUGHT_END in text else text
    if "<|channel>" in body:
        return None, "unfinished_thinking"
    body = body.split(TURN_END, 1)[0].strip()
    for cand in (body, body[body.find("{"): body.rfind("}") + 1] if "{" in body else ""):
        if not cand:
            continue
        try:
            return parse_z(cand), "ok"
        except (ValueError, KeyError, TypeError):
            continue
    return None, "bad_json"


def clean_z(z: list[Location], files: dict[str, str], em_cfg: dict[str, Any]) -> tuple[list[Location], dict[str, int]]:
    """Keep what can be read offline: known paths, line ranges inside the file; then the z rules."""
    stats = {"unknown_path": 0, "clamped": 0}
    out: list[Location] = []
    for loc in z:
        p = normalize_path(loc.path)
        text = files.get(p)
        if text is None:
            stats["unknown_path"] += 1
            continue
        n = max(1, len(text.splitlines()))
        a, b = sorted((loc.start, loc.end))
        a2, b2 = min(max(1, a), n), min(max(1, b), n)
        if (a2, b2) != (loc.start, loc.end):
            stats["clamped"] += 1
        role = "edit" if loc.role == "edit" else "context"
        out.append(Location(p, loc.symbol, a2, b2, role))
    seen: set[tuple] = set()
    uniq = []
    for loc in out:
        if key(loc) not in seen:
            seen.add(key(loc))
            uniq.append(loc)
    pruned = prune(uniq, files, max_locations=em_cfg.get("max_locations", 8),
                   budget_tokens=em_cfg.get("ctx_budget_tokens", 6000))
    stats["pruned"] = len(uniq) - len(pruned)
    return pruned, stats


def z_key(z: list[Location]) -> tuple:
    """Identity of a candidate: the ordered locations (order sets the fixer's read order)."""
    return tuple(key(x) + (x.end, x.role) for x in z)


@dataclass
class Candidate:
    cand_id: int
    source: str                                 # teacher | sample | edit_only | view_only | gold_minus_one
    z: list[Location]
    sample_index: int | None = None

    def to_json(self) -> dict[str, Any]:
        return {"cand_id": self.cand_id, "source": self.source, "sample_index": self.sample_index,
                "z": [x.to_json() for x in self.z]}


@dataclass
class Assembled:
    candidates: list[Candidate]
    stats: dict[str, Any] = field(default_factory=dict)


def assemble(z_teacher: list[Location], samples: list[str], perturbations: dict[str, list[Location]],
             files: dict[str, str], em_cfg: dict[str, Any], k: int | None = None) -> Assembled:
    k = int(k if k is not None else em_cfg.get("K", 8))
    cands = [Candidate(0, "teacher", list(z_teacher))]
    seen = {z_key(z_teacher)}
    st: dict[str, Any] = {"samples": len(samples), "parse": {}, "unknown_path": 0, "clamped": 0, "pruned": 0,
                          "empty": 0, "duplicate": 0, "n_samples_equal_teacher": 0}
    for i, text in enumerate(samples):
        z, why = parse_sample(text)
        st["parse"][why] = st["parse"].get(why, 0) + 1
        if z is None:
            continue
        z, cs = clean_z(z, files, em_cfg)
        for kk in ("unknown_path", "clamped", "pruned"):
            st[kk] += cs[kk]
        if not z:
            st["empty"] += 1
            continue
        zk = z_key(z)
        if zk == z_key(z_teacher):
            st["n_samples_equal_teacher"] += 1
        if zk in seen:
            st["duplicate"] += 1
            continue
        if len(cands) >= k + 1:
            continue
        seen.add(zk)
        cands.append(Candidate(len(cands), "sample", z, i))
    st["unique_samples"] = len(cands) - 1
    for name in ("edit_only", "view_only", "gold_minus_one"):
        z = perturbations.get(name)
        if len(cands) >= k + 1 or not z or z_key(z) in seen:
            continue
        seen.add(z_key(z))
        cands.append(Candidate(len(cands), name, list(z)))
    st["candidates"] = len(cands)
    return Assembled(cands, st)


# --------------------------------------------------------------------------- generation (GPU)
def render_prompt_ids(tok, prompt: dict[str, Any]) -> list[int]:
    """Token ids of the localizer's answer prompt, as in training (`render_text`, generation prompt)."""
    from ..render.chat import render_text

    kw = prompt.get("request_params", {}).get("chat_template_kwargs") or {}
    text = render_text(tok, prompt["messages"], prompt.get("tools"), kw, add_generation_prompt=True)
    return tok(text, add_special_tokens=False)["input_ids"]


def generate_samples(tasks, *, ct: str, tokenizer: str, adapters: dict[str, str], n: int, temperature: float,
                     top_p: float, max_tokens: int, seed: int, max_model_len: int, tp: int,
                     gpu_util: float, text_only: bool = False):
    """Yields one row per task: the other fold's localizer, n samples."""
    from vllm import LLM, SamplingParams
    from vllm.inputs import TokensPrompt
    from vllm.lora.request import LoRARequest

    from ..quant.parity import TEXT_ONLY_OVERRIDE
    from ..render.chat import load_tokenizer
    from .folds import other

    tok = load_tokenizer(tokenizer)
    rank = max(int(json.loads((Path(p) / "adapter_config.json").read_text())["r"]) for p in adapters.values())
    kw: dict[str, Any] = dict(model=ct, max_model_len=max_model_len, tensor_parallel_size=tp,
                              gpu_memory_utilization=gpu_util, enable_lora=True, max_loras=len(adapters),
                              max_lora_rank=rank, enable_prefix_caching=True, seed=seed)
    if text_only:
        kw["hf_overrides"] = TEXT_ONLY_OVERRIDE
    llm = LLM(**kw)
    loras = {f: LoRARequest(f"loc_{f}", i + 1, p) for i, (f, p) in enumerate(sorted(adapters.items()))}
    by_fold: dict[str, list] = {}
    for t in tasks:
        by_fold.setdefault(other(t.fold), []).append(t)
    for fold, ts in sorted(by_fold.items()):
        prompts, keep, skipped = [], [], []
        for t in ts:
            ids = render_prompt_ids(tok, t.prompt)
            if len(ids) + max_tokens > max_model_len:
                skipped.append(t)
                continue
            prompts.append(TokensPrompt(prompt_token_ids=ids))
            keep.append((t, len(ids)))
        sp = SamplingParams(n=n, temperature=temperature, top_p=top_p, max_tokens=max_tokens, seed=seed,
                            skip_special_tokens=False)
        outs = llm.generate(prompts, sp, lora_request=loras[fold]) if prompts else []
        for (t, n_prompt), o in zip(keep, outs, strict=True):
            yield {"instance_id": t.instance_id, "trace": t.trace, "fold": t.fold, "localizer": f"loc_{fold}",
                   "prompt_tokens": n_prompt, "texts": [c.text for c in o.outputs],
                   "finish_reasons": [c.finish_reason for c in o.outputs]}
        for t in skipped:
            yield {"instance_id": t.instance_id, "trace": t.trace, "fold": t.fold, "localizer": f"loc_{fold}",
                   "prompt_tokens": None, "texts": [], "finish_reasons": [], "skipped": "prompt_too_long"}


# --------------------------------------------------------------------------- CLI
def add_args_cmd_candidates(p: argparse.ArgumentParser) -> None:
    from ..data.build_common import parse_shard

    p.add_argument("--loc-records", required=True, help="training s3_loc_r0.jsonl (records/locfix/s3_loc_r0.jsonl)")
    p.add_argument("--folds", required=True, help="folds.json (or its folder) from em.fold-split")
    p.add_argument("--ct", required=True, help="the -w4a16-ct checkpoint")
    p.add_argument("--tokenizer", help="tokenizer folder (default: --ct)")
    p.add_argument("--loc-A", required=True, help="exported fold-A localizer (generates for fold B tasks)")
    p.add_argument("--loc-B", required=True, help="exported fold-B localizer (generates for fold A tasks)")
    p.add_argument("--out", required=True, help="samples JSONL")
    p.add_argument("--n", type=int, help="samples per task (default em.K)")
    p.add_argument("--temperature", type=float, help="default em.sample_temperature")
    p.add_argument("--top-p", type=float, default=1.0)
    p.add_argument("--max-tokens", type=int, default=3072, help="answer length cap (thinking + JSON)")
    p.add_argument("--limit", type=int, default=0, help="first N tasks (a quick check)")
    p.add_argument("--shard", type=parse_shard, default=None, help="K/N: every N-th task from K (one GPU each)")
    p.add_argument("--tp", type=int, default=1)
    p.add_argument("--gpu-memory-utilization", type=float, default=0.85)
    p.add_argument("--vllm-text-only", action="store_true", help="serve through Gemma4ForCausalLM (not the harness class)")


def cmd_candidates(args: argparse.Namespace, cfg: dict) -> int:
    from ..data.build_common import in_shard
    from ..runmeta import write_run_meta
    from .folds import load_folds
    from .tasks import read_stage3_tasks

    tasks = read_stage3_tasks(args.loc_records, load_folds(args.folds))
    tasks = [t for i, t in enumerate(tasks) if in_shard(i, args.shard)]
    if args.limit:
        tasks = tasks[: args.limit]
    em = cfg["em"]
    n = args.n or int(em["K"])
    temp = args.temperature if args.temperature is not None else float(em["sample_temperature"])
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    counts = {"tasks": 0, "samples": 0, "skipped": 0}
    with open(out, "w") as f:
        for row in generate_samples(tasks, ct=args.ct, tokenizer=args.tokenizer or args.ct,
                                    adapters={"A": args.loc_A, "B": args.loc_B}, n=n, temperature=temp,
                                    top_p=args.top_p, max_tokens=args.max_tokens, seed=int(cfg["seed"]),
                                    max_model_len=int(cfg["harness"]["max_model_len"]), tp=args.tp,
                                    gpu_util=args.gpu_memory_utilization, text_only=args.vllm_text_only):
            f.write(json.dumps(row, ensure_ascii=False) + "\n")
            counts["tasks"] += 1
            counts["samples"] += len(row["texts"])
            counts["skipped"] += bool(row.get("skipped"))
    write_run_meta(out.parent, cfg, {"candidates": counts, "n": n, "temperature": temp, "top_p": args.top_p,
                                     "shard": args.shard, "loc_A": args.loc_A, "loc_B": args.loc_B})
    print(json.dumps(counts, indent=2))
    return 0
