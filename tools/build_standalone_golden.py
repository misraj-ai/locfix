"""Build notebooks/golden_render_check_standalone.py: one file with the renderer and the fixture
records embedded, for Kaggle notebooks where only a single script is uploaded.

    python tools/build_standalone_golden.py
"""
from __future__ import annotations

import base64
import gzip
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    chat = (ROOT / "src/locfix/render/chat.py").read_text()
    chat = chat.split('"""', 2)[2]                       # drop the module docstring
    chat = chat.replace("from __future__ import annotations\n", "")
    check = (ROOT / "notebooks/golden_render_check.py").read_text()
    records = b"".join((ROOT / "tests/fixtures/records" / n).read_bytes()
                       for n in ("s1_fixtures.jsonl", "locfix_fixtures.jsonl"))
    blob = base64.b64encode(gzip.compress(records, 9)).decode()
    blob_lines = "\n".join(blob[i:i + 100] for i in range(0, len(blob), 100))

    # the check script without its repo-path bootstrap and with the renderer import replaced
    body = check.split('"""', 2)[2].replace("from __future__ import annotations\n", "")
    body = re.sub(r"REPO = Path\(__file__\).*?DEFAULT_RECORDS = [^\n]*\n", "", body, flags=re.S)
    body = body.replace("    from locfix.render.chat import load_tokenizer, render_record, render_text\n", "")
    body = body.replace("DEFAULT_RECORDS", "_default_records()")
    body = body.replace('default=str(_default_records())', 'default=None')
    body = body.replace("    recs = load_records(records)",
                        "    recs = load_records(records or _default_records())")
    body = body.replace("def check(model: str, records: str | Path = _default_records(),",
                        "def check(model: str, records: str | Path | None = None,")

    out = f'''"""Golden render check, standalone (generated by tools/build_standalone_golden.py; do not edit).

Compares our prompt token ids with vLLM's /v1/chat/completions/render at every trained turn of
the fixture records (embedded below: Stage 1 agent records and localizer/fixer records). Needs vLLM 0.19.1 and transformers 5.13.1 (Kaggle
competition environment). Usage in a Kaggle cell after uploading this file:

    !python golden_render_check_standalone.py \\
        --model /kaggle/input/models/google/gemma-4/other/gemma-4-e4b-it-qat-w4a16-ct/2

Writes golden_render_report.json (and vllm_golden.log) to /kaggle/working.
"""
from __future__ import annotations

# ---------------------------------------------------------------- renderer (src/locfix/render/chat.py)
{chat}

# ---------------------------------------------------------------- embedded fixture records
_RECORDS_GZ_B64 = """
{blob_lines}
"""


def _default_records() -> str:
    import base64 as _b64
    import gzip as _gz
    import tempfile as _tf
    data = _gz.decompress(_b64.b64decode("".join(_RECORDS_GZ_B64.split())))
    f = _tf.NamedTemporaryFile("wb", suffix=".jsonl", delete=False)
    f.write(data)
    f.close()
    return f.name


# ---------------------------------------------------------------- check (notebooks/golden_render_check.py)
{body}'''
    dest = ROOT / "notebooks/golden_render_check_standalone.py"
    dest.write_text(out)
    print(f"wrote {dest} ({len(out) // 1024} KB)")


if __name__ == "__main__":
    main()
